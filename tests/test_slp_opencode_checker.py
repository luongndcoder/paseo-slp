class AgentFileTests(unittest.TestCase):
    def test_frontmatter(self) -> None:
        front, text, _ = generated_agent()
        self.assertEqual(front["mode"], "primary")
        self.assertEqual(front["steps"], 40)
        perm = front["permission"]
        self.assertEqual((perm["edit"], perm["task"], perm["webfetch"]), ("deny", "deny", "deny"))
        self.assertIn("ROLE-MARKER: slp-opencode-checker", text)
        self.assertIn("GENERATED by paseo-slp/bin/slp-build from roles/opencode-checker", text)

    def test_bash_rules_are_fully_open(self) -> None:
        front, _text, _ = generated_agent()
        self.assertEqual(front["permission"]["bash"], {"*": "allow"})  # 2026-11-18: no allowlist, no denies
        self.assertEqual(front["permission"]["edit"], "deny")  # edit stays denied for this role

    def test_deny_by_default_ordering_via_fixture_allowlist(self) -> None:
        """The generic allowlist ordering (catch-all deny, allows, then denies) is still the generator's contract."""
        fixture = {"role": "x", "bash": "allowlist", "bash_allow": ["git diff*", "ls*"], "bash_deny": ["git diff --output*"]}
        rules = build.opencode_bash_rules(fixture)
        self.assertEqual(list(rules), ["*", "git diff*", "ls*", "git diff --output*"])
        self.assertEqual(rules["*"], "deny")
        self.assertEqual(evaluate(rules, "git diff a"), "allow")
        self.assertEqual(evaluate(rules, "git diff --output=/x"), "deny")
        self.assertEqual(evaluate(rules, "touch x"), "deny")

    def test_semantics_last_match_wins(self) -> None:
        rules = generated_agent()[0]["permission"]["bash"]
        for ok in ("touch x", "git push origin HEAD", "git commit -m x", "git push --force origin master", "rm -rf x",
                   "sh -c id", "cat a > b"):  # fmt: skip
            self.assertEqual(evaluate(rules, ok), "allow", ok)
        # evaluator semantics, exercised on a fixture allowlist that reproduces the old checker rules
        rules = build.opencode_bash_rules(
            {"role": "x", "bash": "allowlist", "bash_allow": OLD_ALLOW, "bash_deny": OLD_DENY})
        for ok in ("git diff", "git diff abc123...HEAD -- src/a.py", "git log --oneline -5", "git show HEAD:src/a.py",
                   "git status --short", "git rev-parse HEAD", "git branch --show-current", "cat src/a.py", "ls", "ls -la src",
                   "rg -n merchant_id src", "grep -rn foo .", "head -n 20 a.py", "tail -n 5 a.py", "wc -l a.py"):  # fmt: skip
            self.assertEqual(evaluate(rules, ok), "allow", ok)
        for bad in ("touch x", "git push origin HEAD", "git commit -m x", "git checkout main", "git branch -D x", "git branch foo",
                    "git reset --hard", "python3 -c pass", "sh -c id", "rm -rf x", "curl http://x", "lsof", "catx a", "sed -i s/a/b/ f",
                    "git diff --output=/tmp/x", "git log --output /tmp/x", "git diff --ext-diff", "git show --textconv HEAD:a",
                    "rg --pre sh foo", "rg --pre=sh foo", "rg --pre-glob '*.x' foo", "cat a > b", "cat a >> b", "echo $(id)",
                    "cat `id`", "tee x", "git -C /tmp push"):  # fmt: skip
            self.assertEqual(evaluate(rules, bad), "deny", bad)
        self.assertEqual(evaluate(rules, "git log --pretty=oneline -3"), "allow")  # `--pre` deny must not catch --pretty

    def test_builder_rules_unchanged_and_push_rule_last(self) -> None:
        rules = build.opencode_bash_rules(ROLES["opencode-builder"])
        self.assertEqual(rules, {"*": "allow"})  # 2026-11-18: builder bash_deny emptied, push allowed
        self.assertEqual(evaluate(rules, "pytest -q"), "allow")
        self.assertEqual(evaluate(rules, "git push"), "allow")
        # a fixture policy that opts into the push block still gets the rule LAST (library behaviour)
        blocked = {**ROLES["opencode-builder"], "git_push_block": True}
        with tempfile.TemporaryDirectory() as tmp, mock.patch.object(build, "BUILD_DIR", Path(tmp)):
            build.opencode_provider(blocked)
            text = (Path(tmp) / "opencode" / f"{blocked['agent_name']}.md").read_text()
        order = list(yaml.safe_load(text.split("---\n")[1])["permission"]["bash"].items())
        self.assertEqual(order[-1], ("*git*push*", "deny"))

    def test_bash_rules_modes(self) -> None:
        self.assertEqual(build.opencode_bash_rules({"role": "x", "bash": "none"}), {"*": "deny"})
        self.assertEqual(
            build.opencode_bash_rules({"role": "x", "bash": "allowlist", "bash_allow": ["ls"], "bash_deny": ["ls -R*", "ls"]}),
            {"*": "deny", "ls -R*": "deny", "ls": "deny"},  # a deny re-listed as allow is moved behind the allows
        )
        with self.assertRaises(SystemExit):
            build.opencode_bash_rules({"role": "x", "bash": "readonly"})


class SpawnAndPromptTests(unittest.TestCase):
    def test_lead_may_spawn_the_checker_provider(self) -> None:
        self.assertIn("slp-opencode-checker", ROLES["lead"]["spawn_allow"])
        gp = slp_policy.guard_policy(ROLES["lead"])
        for provider in ("slp-opencode-checker", "slp-opencode-checker/opencode-go/deepseek-v4.1-flash"):
            guard.check_spawn("create_agent", {"provider": provider, "initialPrompt": "x"}, gp)
        with self.assertRaises(guard.Block):
            guard.check_spawn("create_agent", {"provider": "slp-opencode-checkerx", "initialPrompt": "x"}, gp)

    def test_supervisor_cannot_spawn_it(self) -> None:
        self.assertNotIn("slp-opencode-checker", ROLES["supervisor"]["spawn_allow"])

    def test_role_prompt(self) -> None:
        text = (ROOT / "roles/opencode-checker/role.md").read_text()
        flat = re.sub(r"\s+", " ", text)
        self.assertLessEqual(len(text.splitlines()), 60)
        self.assertEqual(text.splitlines()[0], "ROLE-MARKER: slp-opencode-checker")
        for needle in ("git rev-parse HEAD", "head_sha", "base_ref", "merchant_id", "Tenant isolation", "CANNOT write files",
                       "FINAL message", "the Lead saves it", "exact text of that line", "never ask the user"):  # fmt: skip
            self.assertIn(needle, flat)
        self.assertNotIn("Write tool", text)

    def test_playbook_names_the_deepseek_checker_and_no_glm(self) -> None:
        skill = (ROOT / "skills/slp-lead/SKILL.md").read_text()
        profiles = (ROOT / "skills/slp-lead/references/profiles.md").read_text()
        prompts = (ROOT / "skills/slp-lead/references/prompts.md").read_text()
        for text in (skill, profiles, prompts):
            self.assertIn("slp-checker-deepseek", text)
        self.assertIn("get_agent_activity", skill)
        self.assertIn("Kimi K3", skill)
        self.assertRegex(profiles, r"(?m)^\| slp-checker-deepseek \| `slp-opencode-checker/opencode-go/deepseek-v4\.1-flash` \| slp-checker \|")
        files = [*ROOT.joinpath("roles").glob("*/role.md"), *ROOT.joinpath("roles").glob("*/policy.yaml"),
                 *ROOT.joinpath("skills").rglob("*.md"), ROOT / "README.md"]  # fmt: skip
        for path in files:
            self.assertNotRegex(path.read_text(), r"(?i)glm", str(path))


