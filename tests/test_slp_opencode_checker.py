def load(name: str, path: Path):
    loader = importlib.machinery.SourceFileLoader(name, str(path))
    spec = importlib.util.spec_from_loader(name, loader)
    mod = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
    loader.exec_module(mod)
    return mod


build = load("slp_build_oc", ROOT / "bin" / "slp-build")
guard = load("slp_guard_oc", ROOT / "hooks" / "slp-guard.py")
ROLES = build.load_roles()
CHECKER = ROLES["opencode-checker"]


def evaluate(rules: dict[str, str], command: str) -> str:
    """OpenCode semantics: the LAST rule whose glob matches the command wins (`*` = any run of characters)."""
    verdict = "ask"
    for pattern, effect in rules.items():
        regex = ".*".join(re.escape(part) for part in pattern.split("*"))
        if re.fullmatch(regex, command, re.S):
            verdict = effect
    return verdict


def generated_agent() -> tuple[dict, str, dict]:
    with tempfile.TemporaryDirectory() as tmp, mock.patch.object(build, "BUILD_DIR", Path(tmp)):
        providers = build.generate()
        text = (Path(tmp) / "opencode" / "slp-checker.md").read_text()
    front = yaml.safe_load(text.split("---\n")[1])
    return front, text, providers


